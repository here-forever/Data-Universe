const resources: Record<Language, Record<TranslationKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

type TranslationValues = Record<string, string | number>;

export function translate(
  language: Language,
  key: TranslationKey,
  values: TranslationValues = {},
): string {
  const template = resources[language][key] ?? resources["zh-CN"][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

export function useI18n() {
  const language = useWorkspaceStore((state) => state.language);
  const setLanguage = useWorkspaceStore((state) => state.setLanguage);
  const t = useCallback(
    (key: TranslationKey, values?: TranslationValues) =>
      translate(language, key, values),
    [language],
  );
  const formatNumber = useCallback(
    (value: number, options?: Intl.NumberFormatOptions) =>
      value.toLocaleString(language, options),
    [language],
  );
  const formatDateTime = useCallback(
    (value: string | number | Date) =>
      new Date(value).toLocaleString(language, {
        month: "numeric",
        day: "numeric",
        hour: "2-digit",
        minute: "2-digit",
      }),
    [language],
  );

  return { formatDateTime, formatNumber, language, setLanguage, t };
}
